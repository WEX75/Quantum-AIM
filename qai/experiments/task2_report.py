"""Collect every Task 2 result into results/task2/TABLES.md: protocol tables (mean +- std over seeds) for every
model and noise level, and the cost ledger against the baseline. Reads only the CSVs the experiments wrote.

    python3 -m qai.experiments.task2_report
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

OUT = Path("results/task2")
HEADLINE = ["AUPRC", "AUROC", "Spearman rho", "precision", "recall", "F1", "MCC"]


def md(df, index=True):
    """DataFrame -> markdown table (no tabulate dependency)."""
    df = df.reset_index() if index else df
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(map(str, row)) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def protocol_tables():
    frames = [pd.read_csv(f) for f in sorted(OUT.glob("*_per_seed*.csv")) if "_fast" not in f.name]
    if not frames:
        return "no protocol results yet\n"
    df = pd.concat(frames).drop_duplicates(subset=["model", "seed", "p"])
    stats = df.groupby(["model", "p"])[HEADLINE].agg(["mean", "std"])
    cells = pd.DataFrame({m: stats[(m, "mean")].map("{:.3f}".format) + " ± " + stats[(m, "std")].map("{:.3f}".format)
                          for m in HEADLINE})
    seeds = df.groupby("model").seed.nunique()
    out = []
    for model, t in cells.groupby(level="model"):
        out.append(f"### {model} ({seeds[model]} seeds)\n\n" + md(t.droplevel("model")) + "\n")
    focus = stats.xs("AUPRC", axis=1, level=0)
    pivot = (focus["mean"].map("{:.3f}".format) + " ± " + focus["std"].map("{:.3f}".format)).unstack("p")
    return "## Test AUPRC by noise level\n\n" + md(pivot) + "\n\n## Full protocol tables\n\n" + "\n".join(out)


def ledger_table():
    files = [f for f in sorted(OUT.glob("ledger_*.csv")) if "_fast" not in f.name]
    if not files:
        return "no ledger yet\n"
    led = pd.concat([pd.read_csv(f) for f in files]).drop_duplicates("method")
    base = led.loc[led.method == "baseline VQC", "total executions"]
    if len(base):
        led["vs baseline"] = (100 * (led["total executions"] / base.iloc[0] - 1)).map("{:+.1f}%".format)
    for c in ["train executions", "validation executions", "total executions", "total shots",
              "train executions (Tracker)", "total executions (Tracker)"]:
        if c in led:
            led[c] = led[c].map(lambda v: "" if pd.isna(v) else f"{v:,.0f}")
    for c in ["executions_per_example", "tracker_per_example"]:
        if c in led:
            led[c] = led[c].map(lambda v: "" if pd.isna(v) else f"{v:g}")
    return md(led, index=False)


def main():
    text = ("# Task 2 results (generated by qai/experiments/task2_report.py)\n\n" + protocol_tables()
            + "\n## Cost ledger (training + validation on hardware, 1024 shots per execution)\n\n" + ledger_table() + "\n")
    for extra in ["shot_tax.csv", "shots_needed.csv", "cv/cv_pooled_auprc.csv"]:
        if (OUT / extra).exists():
            text += f"\n## {extra}\n\n" + md(pd.read_csv(OUT / extra), index=False) + "\n"
    (OUT / "TABLES.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
